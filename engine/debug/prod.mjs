import { createRequire } from 'node:module';
const { chromium } = createRequire('/home/user/Krita-Web-Port/web/tests/x.mjs')('playwright');
const S = process.argv[2];
const browser = await chromium.launch({ args: ['--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 }, deviceScaleFactor: 2 });
const log = [];
page.on('pageerror', e => log.push('PAGEERROR ' + e.message));
const t0 = Date.now();
await page.goto('http://localhost:8080/krita/');
await page.waitForSelector('canvas.view', { timeout: 150000 });
await page.waitForFunction(() => document.body.innerText.includes('RGBA'), null, { timeout: 150000 });
console.log('ready after', Date.now() - t0, 'ms');
await page.waitForTimeout(5000);
const box = await page.locator('canvas.view').boundingBox();
const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
await page.mouse.move(cx - 150, cy - 60); await page.mouse.down();
for (let i = 0; i <= 30; i++) await page.mouse.move(cx - 150 + i * 10, cy - 60 + Math.sin(i / 4) * 60);
await page.mouse.up(); await page.waitForTimeout(1500);
await page.screenshot({ path: `${S}/prod.png` });
await page.getByRole('menuitem', { name: 'Layer', exact: true }).first().click().catch(()=>page.getByText('Layer', { exact: true }).first().click()); await page.waitForTimeout(1200);
await page.screenshot({ path: `${S}/prod-menu.png` });
console.log(log.join('\n') || 'no page errors');
await browser.close();
