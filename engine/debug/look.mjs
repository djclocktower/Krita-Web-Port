import { createRequire } from 'node:module';
const { chromium } = createRequire('/home/user/Krita-Web-Port/web/tests/x.mjs')('playwright');
const browser = await chromium.launch({ args: ['--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
const errs = []; page.on('pageerror', e => errs.push(e.message.slice(0, 200)));
await page.goto('http://localhost:5173/?engine=wasm');
await page.waitForFunction(() => window.__engine && __engine.documentInfo().then(Boolean), null, { timeout: 150000 });
await page.waitForTimeout(3500);
const box = await page.locator('canvas.view').boundingBox();
const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
await page.mouse.move(cx - 150, cy - 60); await page.mouse.down();
for (let i = 0; i <= 30; i++) await page.mouse.move(cx - 150 + i * 10, cy - 60 + Math.sin(i / 4) * 60);
await page.mouse.up(); await page.waitForTimeout(1000);
await page.evaluate(() => __engine.showKritaDocker('ColorSelectorNg', true)); await page.waitForTimeout(2500);
await page.locator('[data-krita-tool="KisToolTransform"]').click(); await page.waitForTimeout(3000);
await page.screenshot({ path: `${process.argv[2]}/look-1.png` });
await page.locator('[data-krita-tool="SvgTextTool"]').click(); await page.waitForTimeout(9000);
await page.screenshot({ path: `${process.argv[2]}/look-2.png` });
console.log(errs.join('\n') || 'no page errors');
await browser.close();
